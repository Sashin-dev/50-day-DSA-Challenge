// @lc code=start
class Solution {
    public int maxArea(int[] height) {
        int left = 0;
        int right = height.length - 1;
        int maxAreaSoFar = 0;
        while (right > left) {
            maxAreaSoFar = Math.max(maxAreaSoFar, (right - left) * Math.min(height[left], height[right]));
            if (height[left] < height[right]) {
                left++;
            } else {
                right--;
            }
        }
        return maxAreaSoFar;
    }
}
